export const LABELS: Readonly<Record<DocLanguage, Labels>> = { en: EN, pl: PL, de: DE };

/** A label in a language, its `{name}` placeholders filled (the prototype's `t`). */
export function label(language: DocLanguage, key: LabelKey, values: Readonly<Record<string, string | number>> = {}): string {
  return LABELS[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
